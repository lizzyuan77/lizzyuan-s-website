"""
06_text_values.py  -  Write every number quoted in index.qmd to results/text_values.yml.

index.qmd loads that file (metadata-files) and shows each value with Quarto's
{{< meta key >}} shortcode, so the article text is generated from results/
and rendering the page needs only Quarto (no R or Python at render time).
Also writes the small fictional tables as Markdown includes.

Run from the post6 folder after 04_estimate.py:  python code/06_text_values.py
"""
from pathlib import Path

import pandas as pd

RES = Path(__file__).resolve().parents[1] / "results"
rd = lambda f: pd.read_csv(RES / f)


def one(s):
    assert len(s) == 1, f"expected one value, got {len(s)}"
    return s.iloc[0]


f2 = lambda x: f"{x:.2f}"
n0 = lambda x: f"{round(x):,}"

r, yr, dif = rd("ige_results.csv"), rd("ige_by_year.csv"), rd("ige_differences.csv")
flow, jc, cor = rd("sample_flow.csv"), rd("join_checks.csv"), rd("year_to_year_correlation.csv")
sens, tc = rd("ige_bottomcode_sensitivity.csv"), rd("table_counts.csv")

ige = lambda g, s: one(r.loc[(r.group == g) & (r.spec == s), "ige"])
by = lambda g, y, k="ige": one(yr.loc[(yr.group == g) & (yr.income_year == y), k])
gap = lambda k: one(dif.loc[(dif.group == "daughters minus sons")
                            & (dif.comparison == "Three-year averages"), k])
sv = lambda t, s: one(sens.loc[(sens.group == "sons") & sens.treatment.str.startswith(t)
                               & (sens.spec == s), "ige"])
jn = lambda t, k="n_rows": one(jc.loc[jc.tbl == t, k])

v = {
    "people": n0(one(tc.loc[tc.table == "people", "rows"])),
    "pairs": n0(jn("pairs")),
    "trap_rows": n0(jn("naive_year_by_year_join")),
    "trap_children": n0(jn("naive_year_by_year_join", "n_children")),
    "n_daughters": n0(one(flow.loc[flow.step == 7, "daughter"])),
    "n_sons": n0(one(flow.loc[flow.step == 7, "son"])),
    "d_single": f2(ige("daughters", "Single year")),
    "d_avg": f2(ige("daughters", "Three-year averages")),
    "s_single": f2(ige("sons", "Single year")),
    "s_avg": f2(ige("sons", "Three-year averages")),
    "a_single": f2(ige("all children", "Single year")),
    "a_avg": f2(ige("all children", "Three-year averages")),
    "cor_parent": f2(one(cor.loc[(cor.year_a == 1980) & (cor.year_b == 1982), "corr_log_income"])),
    "bad_single": f2(sv("$1 code treated as income", "Single year")),
    "ok_single": f2(sv("$1 code treated as no income", "Single year")),
    "bad_avg": f2(sv("$1 code treated as income", "Three-year averages")),
    "ok_avg": f2(sv("$1 code treated as no income", "Three-year averages")),
    "fixed_n": n0(by("all children", 2000, "n")),
    "s_2000": f2(by("sons", 2000)), "s_2014": f2(by("sons", 2014)),
    "s_age_2000": f"{by('sons', 2000, 'mean_age'):.0f}",
    "s_age_2014": f"{by('sons', 2014, 'mean_age'):.0f}",
    "d_2000": f2(by("daughters", 2000)), "d_2014": f2(by("daughters", 2014)),
    "gap": f2(abs(gap("difference"))),
    "gap_lo": f2(gap("ci_low")), "gap_hi": f2(gap("ci_high")),
}
with open(RES / "text_values.yml", "w") as f:
    f.write("# Generated by code/06_text_values.py from results/*.csv. Do not edit by hand.\n")
    for k, val in v.items():
        f.write(f'v_{k}: "{val}"\n')


def md_table(df):
    df = df.astype(str)
    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * df.shape[1]]
    lines += ["| " + " | ".join(row) + " |" for row in df.values]
    return "\n".join(lines) + "\n"


# Underscore prefix: Quarto includes these but never renders them as pages
(RES / "_toy_pairs.md").write_text(md_table(rd("toy_pairs.csv")))
s = rd("toy_parent_summary.csv")
s["parent_mean"] = s["parent_mean"].map(lambda x: f"{x:,.0f}")
s["parent_single"] = s["parent_single"].map(lambda x: f"{x:,.0f}")
(RES / "_toy_parent_summary.md").write_text(md_table(s))
print(f"wrote {len(v)} text values and 2 tables")
